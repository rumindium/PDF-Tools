import { describe, expect, test } from 'bun:test';
import { buildZip, readZipDirectory } from './zip-writer';

/**
 * The ZIP writer's own guarantees, checked against its bytes.
 *
 * A fixture archive is only useful if it is a *real* archive, and the failure that matters is silent: a wrong CRC or
 * a central-directory offset pointing at the wrong place produces a file that opens in one tool and is rejected by
 * another. `unzip` is not in any of the worker images, so the round trip here is the writer's own reader plus the
 * structural facts the format fixes — and the real consumer (Python's `zipfile`, inside the office worker) is the
 * one the golden case exercises.
 */
describe('buildZip', () => {
  test('writes one local header per entry, in order, with the central directory after the data', () => {
    const bytes = buildZip([
      { name: 'index.html', content: '<html><body>one</body></html>' },
      { name: 'styles.css', content: 'body { color: #333; }' },
    ]);

    const names = readZipDirectory(bytes);
    expect(names.map((entry) => entry.name)).toEqual(['index.html', 'styles.css']);

    // The end-of-central-directory record is the last 22 bytes and points at the directory.
    const buffer = Buffer.from(bytes);
    const end = buffer.indexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
    expect(end).toBeGreaterThan(0);
    expect(end + 22).toBe(bytes.length);
    const entries = buffer.readUInt16LE(end + 10);
    const directoryOffset = buffer.readUInt32LE(end + 16);
    expect(entries).toBe(2);
    expect(buffer.subarray(directoryOffset, directoryOffset + 4)).toEqual(Buffer.from([0x50, 0x4b, 0x01, 0x02]));
  });

  test('the stored CRC matches the entry it describes', () => {
    const content = 'checked byte for byte';
    const bytes = buildZip([{ name: 'notes.txt', content }]);
    const [entry] = readZipDirectory(bytes);
    expect(entry?.size).toBe(Buffer.byteLength(content, 'utf8'));

    // Recomputed independently: the standard reflected polynomial, over the stored payload.
    let crc = 0xffffffff;
    for (const byte of Buffer.from(content, 'utf8')) {
      crc ^= byte;
      for (let bit = 0; bit < 8; bit += 1) crc = crc & 1 ? 0xedb88320 ^ (crc >>> 1) : crc >>> 1;
    }
    expect(entry?.crc).toBe((crc ^ 0xffffffff) >>> 0);
  });

  test('a path with a directory component round trips, so a bundle can carry its assets', () => {
    const bytes = buildZip([{ name: 'assets/site.css', content: 'p { margin: 0; }' }]);
    expect(readZipDirectory(bytes).map((entry) => entry.name)).toEqual(['assets/site.css']);
  });

  test('the same input always produces the same bytes', () => {
    // Fixtures are regenerated by CI and compared by case, so a timestamp taken from the clock would make two runs
    // of the same fixture differ — the defect the fixed DOS date exists to prevent.
    const once = buildZip([{ name: 'a.html', content: '<p>same</p>' }]);
    const twice = buildZip([{ name: 'a.html', content: '<p>same</p>' }]);
    expect(Buffer.from(once).equals(Buffer.from(twice))).toBe(true);
  });
});
